const baileys = require('@whiskeysockets/baileys');
const fetch = globalThis.fetch;

// Owner check — uses ctx.isOwner if your framework provides it, otherwise
// falls back to comparing the sender's number against OWNER_NUMBERS
// (comma-separated, e.g. OWNER_NUMBERS=2348012345678,2349098765432).
function isOwner(ctx) {
    if (typeof ctx.isOwner === 'boolean') return ctx.isOwner;
    const raw = ctx.sender || '';
    const num = raw.split('@')[0].split(':')[0].replace(/\D/g, '');
    const owners = (process.env.OWNER_NUMBERS || '')
        .split(',')
        .map(s => s.replace(/\D/g, ''))
        .filter(Boolean);
    return num.length > 0 && owners.includes(num);
}

// Helper: Upload image to Catbox
async function uploadToCatbox(buffer) {
    const form = new FormData();
    form.append('reqtype', 'fileupload');
    form.append('fileToUpload', new Blob([buffer]), 'image.jpg');
    const res = await fetch('https://catbox.moe/user/api.php', { method: 'POST', body: form });
    if (!res.ok) throw new Error('Catbox upload failed');
    const url = await res.text();
    if (!url.startsWith('https://')) throw new Error('Catbox returned invalid URL');
    return url.trim();
}

module.exports = {
    name: 'roar',
    category: 'ai',
    description: 'Modify an image using AI (Image-to-Image)',
    aliases: ['img2img', 'edit'],
    async execute(sock, msg, args, ctx) {
        // Parse --nsfw / -n out of args; remaining tokens form the prompt
        let nsfwRequested = false;
        const promptParts = [];
        for (const a of args) {
            if (a === '--nsfw' || a === '-n') nsfwRequested = true;
            else promptParts.push(a);
        }
        const prompt = promptParts.join(' ').trim();

        if (!prompt) {
            return sock.sendMessage(ctx.sender, {
                text: 'Usage: Reply to an image with ' + ctx.prefix + 'roar <prompt>\n' +
                      'Example: ' + ctx.prefix + 'roar Turn this into an anime character\n' +
                      'Owner-only: ' + ctx.prefix + 'roar --nsfw <prompt>'
            });
        }

        // Owner gate — regular users can never reach NSFW, even by guessing the flag
        if (nsfwRequested && !isOwner(ctx)) {
            return sock.sendMessage(ctx.sender, { text: '❌ --nsfw is owner-only.' });
        }

        const quoted = msg.message.extendedTextMessage?.contextInfo?.quotedMessage;
        const imageMsg = quoted?.imageMessage || msg.message.imageMessage;

        if (!imageMsg) return sock.sendMessage(ctx.sender, { text: '❌ Please reply to an image.' });

        await sock.sendMessage(ctx.sender, { text: '🎨 Processing image with AI...' });

        try {
            // 1. Download original image
            const stream = await baileys.downloadContentFromMessage(imageMsg, 'image');
            let buffer = Buffer.from([]);
            for await (const chunk of stream) buffer = Buffer.concat([buffer, chunk]);

            // 2. Upload to Catbox
            const imageUrl = await uploadToCatbox(buffer);
            console.log('Catbox URL:', imageUrl);

            // 3. Send to API — nsfw is true only when owner + flag present
            const nsfw = nsfwRequested && isOwner(ctx);
            const apiUrl = `https://api.omegatech.app/api/ai/roar?action=text-to-image&mode=image-to-image&type=image-to-image&prompt=${encodeURIComponent(prompt)}&size=512x512&quality=best&sampler=k_euler&nsfw=${nsfw}&image2=${encodeURIComponent(imageUrl)}&fit_mode=cover`;

            const res = await fetch(apiUrl, { headers: { 'User-Agent': 'Mozilla/5.0' }, signal: AbortSignal.timeout(120000) });
            const data = await res.json();
            console.log('ROAR RESPONSE:', JSON.stringify(data, null, 2));

            if (!data.success || !data.data || !data.data.images || data.data.images.length === 0) {
                throw new Error('No image generated by the API.');
            }

            const resultUrl = data.data.images[0].url;

            // 4. Download result and send
            const imgRes = await fetch(resultUrl);
            const resultBuffer = Buffer.from(await imgRes.arrayBuffer());

            await sock.sendMessage(ctx.sender, {
                image: resultBuffer,
                caption: '🎨 *AI Edit:* ' + prompt
            });

        } catch (e) {
            console.log('Roar error:', e.message);
            await sock.sendMessage(ctx.sender, { text: '❌ Roar Error: ' + e.message });
        }
    }
};
